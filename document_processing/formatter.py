"""Shared document formatting helpers."""

from __future__ import annotations

import re
from typing import List, Tuple

from backend.utils.sanitizers import sanitize_text


DISCLAIMER = (
    "LegalEase generates AI-assisted legal-document drafts for informational "
    "and drafting purposes. Review the document with a qualified legal "
    "professional where appropriate."
)


def normalize_content(content: str) -> str:
    return sanitize_text(content)


def split_into_blocks(content: str) -> List[str]:
    """Split content into paragraph-like blocks."""
    text = normalize_content(content)
    blocks = [b.strip() for b in re.split(r"\n\s*\n", text) if b.strip()]
    return blocks


def extract_heading_and_body(block: str) -> Tuple[str, str]:
    """If a block starts with a heading-like first line, split it."""
    lines = block.splitlines()
    if not lines:
        return "", ""
    first = lines[0].strip()
    if len(first) < 80 and (
        first.isupper()
        or re.match(r"^\d+[\.\)]\s+\S+", first)
        or re.match(r"^#{1,3}\s+\S+", first)
        or first.endswith(":")
    ):
        heading = re.sub(r"^#{1,3}\s+", "", first).rstrip(":")
        body = "\n".join(lines[1:]).strip()
        return heading, body
    return "", block


def bulletize_lines(text: str) -> List[str]:
    """Return list items from bullet/numbered lines; otherwise one item."""
    lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
    bullets = []
    for line in lines:
        if re.match(r"^[-*•]\s+", line) or re.match(r"^\d+[\.\)]\s+", line):
            bullets.append(re.sub(r"^[-*•\d\.\)\s]+", "", line).strip())
    return bullets if bullets else ([text.strip()] if text.strip() else [])


def build_footer_text() -> str:
    return "Generated by LegalEase - AI-assisted draft. Not legal advice."
